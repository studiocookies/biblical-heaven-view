from datetime import datetime, time, timedelta
from typing import Any

from hotel_agent.models import (
    Channel,
    DataSource,
    FeeKind,
    FeeLine,
    Hotel,
    IncludedBenefit,
    LoyaltyProgramId,
    NormalizedOffer,
    PayableWhen,
    RawOffer,
    Refundability,
    SearchQuery,
)
from hotel_agent.providers.base import HotelSearchProvider

