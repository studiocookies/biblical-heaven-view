# City "expensiveness" tiers. Anything not listed defaults to tier 2 (mid).
_CITY_TIER: dict[str, float] = {
    "new york": 1.45, "new york city": 1.45, "nyc": 1.45,
    "san francisco": 1.4, "london": 1.4, "paris": 1.35, "tokyo": 1.3,
    "los angeles": 1.2, "miami": 1.2, "boston": 1.2, "dubai": 1.25,
    "chicago": 1.0, "seattle": 1.1, "washington": 1.1, "washington dc": 1.1,
    "toronto": 1.0, "barcelona": 1.0, "rome": 1.0, "amsterdam": 1.1,
    "las vegas": 1.05, "orlando": 0.9,
}
_DEFAULT_CITY_TIER = 0.85

# (brand name, class multiplier) per loyalty program, roughly economy -> luxury.
_BRANDS: dict[LoyaltyProgramId, list[tuple[str, float]]] = {
    LoyaltyProgramId.MARRIOTT_BONVOY: [
        ("Fairfield Inn & Suites", 0.55),
        ("Courtyard by Marriott", 0.7),
        ("Marriott Hotel", 1.0),
        ("The Ritz-Carlton", 1.9),
    ],
    LoyaltyProgramId.HILTON_HONORS: [
        ("Hampton Inn", 0.55),
        ("Hilton Garden Inn", 0.7),
        ("Hilton Hotel", 1.0),
        ("Waldorf Astoria", 1.9),
    ],
    LoyaltyProgramId.WORLD_OF_HYATT: [
        ("Hyatt Place", 0.55),
        ("Hyatt House", 0.65),
        ("Hyatt Regency", 1.0),
        ("Park Hyatt", 1.7),
    ],
    LoyaltyProgramId.IHG_ONE_REWARDS: [
        ("Holiday Inn Express", 0.5),
        ("Holiday Inn", 0.65),
        ("Crowne Plaza", 0.95),
        ("InterContinental", 1.4),
    ],
}

_BRAND_DOMAIN: dict[LoyaltyProgramId, str] = {
    LoyaltyProgramId.MARRIOTT_BONVOY: "marriott.com",
    LoyaltyProgramId.HILTON_HONORS: "hilton.com",
    LoyaltyProgramId.WORLD_OF_HYATT: "hyatt.com",
    LoyaltyProgramId.IHG_ONE_REWARDS: "ihg.com",
}

# Points required per night, by program (used for AWARD offers).
_AWARD_POINTS_PER_NIGHT: dict[LoyaltyProgramId, tuple[int, int]] = {
    LoyaltyProgramId.WORLD_OF_HYATT: (12_000, 35_000),
    LoyaltyProgramId.MARRIOTT_BONVOY: (30_000, 70_000),
    LoyaltyProgramId.HILTON_HONORS: (50_000, 95_000),
    LoyaltyProgramId.IHG_ONE_REWARDS: (30_000, 60_000),
}

_INDEPENDENT_NAMES = [
    "The Ashcroft Boutique Hotel", "Harborview Inn", "The Meridian House",
    "Old Town Lodge", "The Wren Hotel", "Cobblestone Manor",
    "The Signal House", "Northgate Suites", "The Lantern Inn",
    "Riverside Boutique Hotel",
]

_OTA_SITES = ["expedia.com", "booking.com"]
_STREET_NAMES = ["Main", "Market", "Oak", "5th", "Harbor", "Union", "Park", "Grand"]


def _slugify(name: str) -> str:
    return "".join(c for c in name.lower() if c.isalnum())


def _stable_seed(destination: str, check_in, check_out) -> int:
    key = f"{destination.strip().lower()}|{check_in.isoformat()}|{check_out.isoformat()}"
    digest = hashlib.sha256(key.encode("utf-8")).hexdigest()
    return int(digest[:16], 16)


class FixtureProvider(HotelSearchProvider):
    """Deterministic mock hotel data generator. NOT a real provider — MOCK DATA."""

    name = "fixtures"

    def is_available(self) -> tuple[bool, str]:
        return True, "built-in fixture data (MOCK) — not a real hotel provider"

    def search(self, query: SearchQuery) -> list[RawOffer]:
        rng = random.Random(_stable_seed(query.destination, query.check_in, query.check_out))
        city_key = query.destination.strip().lower()
        city_tier = _CITY_TIER.get(city_key, _DEFAULT_CITY_TIER)
        city_label = query.destination.strip().title()

        n_hotels = rng.randint(6, 9)
        programs = list(_BRANDS.keys())

        # Guarantee coverage of all four chain programs, plus 1-2 independents,
        # then fill the remainder with random (possibly repeated) programs.
        plan: list[LoyaltyProgramId | None] = list(programs)
        n_independent = rng.randint(1, 2)
        plan.extend([None] * n_independent)
        while len(plan) < n_hotels:
            plan.append(rng.choice(programs + [None]))
        plan = plan[:n_hotels]
        rng.shuffle(plan)

        raw_offers: list[RawOffer] = []
        chain_award_count = 0
        chain_hotel_specs = [p for p in plan if p is not None]

        for i, program in enumerate(plan):
            hotel, brand_tier = self._make_hotel(rng, program, city_tier, city_label, i)
            has_resort_fee = rng.random() < (0.5 if city_tier >= 1.15 else 0.25)

            # Ensure at least 2 chain hotels overall get an AWARD offer.
            remaining_chain_hotels = len([p for p in plan[i:] if p is not None])
            need_more_awards = chain_award_count < 2 and remaining_chain_hotels <= (
                2 - chain_award_count
            )
            give_award = program is not None and (need_more_awards or rng.random() < 0.55)
            if give_award and program is not None:
                chain_award_count += 1

            offers = self._make_offers(
                rng, query, hotel, program, brand_tier, has_resort_fee, give_award
            )
            for offer in offers:
                payload = offer.model_dump(mode="json")
                payload.pop("offer_id", None)
                payload.pop("fetched_at", None)
                raw_offers.append(
                    RawOffer(provider=self.name, data_source=DataSource.FIXTURE, payload=payload)
                )

        return raw_offers

    # -- generation helpers ---------------------------------------------

    def _make_hotel(
        self,
        rng: random.Random,
        program: LoyaltyProgramId | None,
        city_tier: float,
        city_label: str,
        index: int,
    ) -> tuple[Hotel, float]:
        street = f"{rng.randint(100, 2999)} {rng.choice(_STREET_NAMES)} St"
        if program is None:
            name = rng.choice(_INDEPENDENT_NAMES)
            brand = ""
            brand_tier = rng.uniform(0.6, 1.3)
            loyalty = LoyaltyProgramId.NONE
        else:
            brand, brand_tier = rng.choice(_BRANDS[program])
            name = f"{brand} {city_label}" if index % 2 == 0 else f"{brand} Downtown {city_label}"
            loyalty = program

        stars = round(min(5.0, 2.3 + brand_tier * 1.2), 1)
        hotel = Hotel(
            name=name,
            brand=brand,
            program=loyalty,
            city=city_label,
            address=f"{street}, {city_label}",
            stars=stars,
            latitude=None,
            longitude=None,
        )
        return hotel, brand_tier

    def _nightly_base_cents(self, rng: random.Random, city_tier: float, brand_tier: float) -> int:
        dollars = 115.0 * city_tier * brand_tier * rng.uniform(0.85, 1.15)
        return max(4000, round(dollars * 100))

    def _tax_fee(self, rng: random.Random, base_cents: int) -> FeeLine:
        rate = rng.uniform(0.14, 0.17)
        return FeeLine(
            kind=FeeKind.TAX,
            description="Occupancy & sales tax",
            amount_cents=round(base_cents * rate),
            payable=PayableWhen.AT_BOOKING,
            included_in_advertised_total=True,
        )

    def _resort_fee(self, rng: random.Random, nights: int, included: bool) -> FeeLine:
        per_night = rng.randint(2500, 4500)
        return FeeLine(
            kind=FeeKind.RESORT_FEE,
            description="Resort/destination fee",
            amount_cents=per_night * nights,
            payable=PayableWhen.AT_PROPERTY,
            included_in_advertised_total=included,
        )

    def _cancel_deadline(self, check_in) -> datetime:
        return datetime.combine(check_in - timedelta(days=3), time(15, 0))

    def _make_offers(
        self,
        rng: random.Random,
        query: SearchQuery,
        hotel: Hotel,
        program: LoyaltyProgramId | None,
        brand_tier: float,
        has_resort_fee: bool,
        give_award: bool,
    ) -> list[NormalizedOffer]:
        nights = query.nights
        currency = query.currency
        city_tier = _CITY_TIER.get(query.destination.strip().lower(), _DEFAULT_CITY_TIER)
        nightly_base = self._nightly_base_cents(rng, city_tier, brand_tier)
        is_chain = program is not None
        domain = _BRAND_DOMAIN.get(program) if program else f"{_slugify(hotel.name)}.com"

        offers: list[NormalizedOffer] = []

        # 1. Standard direct rate — fully refundable.
        std_base = nightly_base * nights
        std_fees = [self._tax_fee(rng, std_base)]
        if has_resort_fee:
            std_fees.append(self._resort_fee(rng, nights, included=True))
        std_benefits = []
        if brand_tier >= 1.5 and rng.random() < 0.6:
            std_benefits.append(
                IncludedBenefit(
                    name="breakfast for 2",
                    est_value_cents=rng.randint(3000, 5000),
                    note="valued conservatively",
                )
            )
        offers.append(
            NormalizedOffer(
                offer_id="",
                provider="fixtures",
                data_source=DataSource.FIXTURE,
                channel=Channel.DIRECT,
                booking_site=domain,
                hotel=hotel,
                room_description="Standard Room, 1 King or 2 Queen Beds",
                rate_plan="Best Available Rate",
                currency=currency,
                base_cents=std_base,
                fees=std_fees,
                refundability=Refundability.FULLY_REFUNDABLE,
                cancel_deadline=self._cancel_deadline(query.check_in),
                included_benefits=std_benefits,
                earns_loyalty=is_chain,
                counts_for_elite_credit=is_chain,
                booking_url=f"https://www.{domain}",
            )
        )

        # 2. Direct member rate — chain only, a little cheaper.
        if is_chain:
            member_nightly = round(nightly_base * rng.uniform(0.92, 0.97))
            member_base = member_nightly * nights
            member_fees = [self._tax_fee(rng, member_base)]
            if has_resort_fee:
                member_fees.append(self._resort_fee(rng, nights, included=True))
            member_benefits = list(std_benefits)
            if not member_benefits and rng.random() < 0.5:
                member_benefits.append(
                    IncludedBenefit(
                        name="breakfast for 2",
                        est_value_cents=rng.randint(3000, 5000),
                        note="valued conservatively",
                    )
                )
            offers.append(
                NormalizedOffer(
                    offer_id="",
                    provider="fixtures",
                    data_source=DataSource.FIXTURE,
                    channel=Channel.DIRECT,
                    booking_site=domain,
                    hotel=hotel,
                    room_description="Standard Room, 1 King or 2 Queen Beds",
                    rate_plan="Member Rate",
                    currency=currency,
                    base_cents=member_base,
                    fees=member_fees,
                    refundability=Refundability.FULLY_REFUNDABLE,
                    cancel_deadline=self._cancel_deadline(query.check_in),
                    included_benefits=member_benefits,
                    earns_loyalty=True,
                    counts_for_elite_credit=True,
                    booking_url=f"https://www.{domain}/member-rate",
                )
            )

        # 3. OTA rate — a few % cheaper, no loyalty earning, resort fee hidden
        #    from the advertised total if one applies.
        ota_nightly = round(nightly_base * rng.uniform(0.90, 0.98))
        ota_base = ota_nightly * nights
        ota_fees = [self._tax_fee(rng, ota_base)]
        if has_resort_fee:
            ota_fees.append(self._resort_fee(rng, nights, included=False))
        ota_refundable = rng.random() < 0.5
        offers.append(
            NormalizedOffer(
                offer_id="",
                provider="fixtures",
                data_source=DataSource.FIXTURE,
                channel=Channel.OTA,
                booking_site=rng.choice(_OTA_SITES),
                hotel=hotel,
                room_description="Standard Room, 1 King or 2 Queen Beds",
                rate_plan="OTA Rate" if ota_refundable else "OTA Non-Refundable Rate",
                currency=currency,
                base_cents=ota_base,
                fees=ota_fees,
                refundability=(
                    Refundability.FULLY_REFUNDABLE if ota_refundable else Refundability.NON_REFUNDABLE
                ),
                cancel_deadline=self._cancel_deadline(query.check_in) if ota_refundable else None,
                included_benefits=[],
                earns_loyalty=False,
                counts_for_elite_credit=False,
                booking_url=f"https://www.{rng.choice(_OTA_SITES)}",
            )
        )

        # 4. Either an AWARD (chain, when selected) or a non-refundable
        #    advance-purchase direct rate — keeps offers/hotel in [2, 4].
        if is_chain and give_award and program in _AWARD_POINTS_PER_NIGHT:
            lo, hi = _AWARD_POINTS_PER_NIGHT[program]
            points_per_night = rng.randint(lo, hi)
            award_cash = rng.randint(0, 4000)
            if has_resort_fee:
                award_cash += self._resort_fee(rng, nights, included=True).amount_cents
            offers.append(
                NormalizedOffer(
                    offer_id="",
                    provider="fixtures",
                    data_source=DataSource.FIXTURE,
                    channel=Channel.AWARD,
                    booking_site=domain,
                    hotel=hotel,
                    room_description="Standard Room, 1 King or 2 Queen Beds",
                    rate_plan="Standard Award Rate",
                    currency=currency,
                    base_cents=0,
                    fees=[],
                    points_cost=points_per_night * nights,
                    award_cash_cents=award_cash,
                    refundability=Refundability.FULLY_REFUNDABLE,
                    cancel_deadline=self._cancel_deadline(query.check_in),
                    included_benefits=[],
                    earns_loyalty=False,
                    counts_for_elite_credit=True,
                    booking_url=f"https://www.{domain}/award",
                )
            )
        elif rng.random() < 0.5:
            nr_nightly = round(nightly_base * rng.uniform(0.85, 0.90))
            nr_base = nr_nightly * nights
            nr_fees = [self._tax_fee(rng, nr_base)]
            if has_resort_fee:
                nr_fees.append(self._resort_fee(rng, nights, included=True))
            offers.append(
                NormalizedOffer(
                    offer_id="",
                    provider="fixtures",
                    data_source=DataSource.FIXTURE,
                    channel=Channel.DIRECT,
                    booking_site=domain,
                    hotel=hotel,
                    room_description="Standard Room, 1 King or 2 Queen Beds",
                    rate_plan="Advance Purchase (Non-Refundable)",
                    currency=currency,
                    base_cents=nr_base,
                    fees=nr_fees,
                    refundability=Refundability.NON_REFUNDABLE,
                    cancel_deadline=None,
                    included_benefits=[],
                    earns_loyalty=is_chain,
                    counts_for_elite_credit=is_chain,
                    booking_url=f"https://www.{domain}/advance-purchase",
                )
            )

        return offers
