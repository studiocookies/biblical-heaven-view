"""FixtureProvider — deterministic MOCK DEMO DATA for offline dev/testing.

*** THIS PROVIDER NEVER TALKS TO A REAL HOTEL API. ***

Every offer it returns is synthetic, generated by a seeded PRNG derived from
the search query (destination + dates), and carries
`DataSource.FIXTURE`. Nothing here is a real rate, real availability, or a
real hotel policy — it exists so the rest of the pipeline (cost engine,
skeptic, recommendation, CLI/UI) can be developed and tested without network
access to a real provider such as Amadeus. `normalize.py`/the pipeline must
keep `DataSource.FIXTURE` offers labelled as mock wherever they reach a user.

Determinism: the same `SearchQuery.destination` + `check_in` + `check_out`
always yields byte-identical generated hotels/offers (same seed -> same
`random.Random` stream), which the test suite relies on.

Offer payload shape: each `RawOffer.payload` is exactly
`NormalizedOffer.model_dump(mode="json")` with the `offer_id` and
`fetched_at` keys removed (`normalize.py` fills those in — `offer_id` from a
stable hash of provider/hotel/channel/rate_plan/room, `fetched_at` stays
`None` for fixture data since it was never actually "fetched").
"""

